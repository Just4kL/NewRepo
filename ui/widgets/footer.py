class FooterBar(QWidget):
    """Компактная строка цитат. Высоту не тянет (Fixed по вертикали)."""

    def __init__(self, parent=None, interval_ms: int = 10000):
        super().__init__(parent)
        layout = QHBoxLayout(self)
        layout.setContentsMargins(0, 0, 0, 0)

        self.label = QLabel(random.choice(QUOTES))
        self.label.setObjectName("FooterLabel")
        self.label.setAlignment(Qt.AlignCenter)
        self.label.setWordWrap(True)
        layout.addWidget(self.label)

        from PyQt5.QtWidgets import QSizePolicy
        self.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Fixed)
        self.setMaximumHeight(40)  # до двух строк — длинные цитаты не режутся

        self._timer = QTimer(self)
        self._timer.timeout.connect(self.rotate)
        self._timer.start(interval_ms)

    def rotate(self):
        """Меняет цитату, не повторяя предыдущую подряд."""
        new_quote = random.choice(QUOTES)
        while new_quote == self.label.text() and len(QUOTES) > 1:
            new_quote = random.choice(QUOTES)
        self.label.setText(new_quote)
